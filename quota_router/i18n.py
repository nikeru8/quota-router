TABLES = {"en": EN, "zh-TW": ZH_TW}


def resolve(config_language=None):
    """$QR_LANG wins, then the config file, then English. Unknown names are skipped."""
    for candidate in (os.environ.get("QR_LANG"), config_language):
        if candidate in TABLES:
            return candidate
    return "en"


_language = resolve()


def set_language(language):
    global _language
    _language = language if language in TABLES else "en"


def language():
    return _language


def t(key, /, **values):
    """The message for `key` in the current language, formatted with `values`."""
    template = TABLES[_language].get(key)
    if template is None:
        template = EN[key]
    return template.format(**values) if values else template


def every(key):
    """`key` in every language, for parsing text that may have been written in another one."""
    return [table[key] for table in TABLES.values() if key in table]
